'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.join(__dirname,'../dist');
const html=fs.readFileSync(path.join(root,'games/word-rescue-unit4.html'),'utf8');
const catalog=JSON.parse(fs.readFileSync(path.join(root,'data.js'),'utf8').replace(/^window\.WQ_CATALOG = /,'').replace(/;\s*$/,''));
const unit=catalog.units.find(u=>u.id==='bir-unit-4');
assert.ok(unit,'Unit 4 must exist');
const words=JSON.parse(fs.readFileSync(path.join(root,unit.dataFile.replace(/^\//,'')),'utf8')).words;
assert.equal(words.length,46);
const bank=html.match(/<script type="application\/json" id="questionData">([\s\S]*?)<\/script>/);
assert.ok(bank,'Unit 4 question data missing');
const qs=JSON.parse(bank[1]);
assert.equal(qs.length,46);
assert.deepEqual(qs.map(q=>q.term).sort(),words.map(w=>w.term).sort());
const types={};
for(const q of qs){
 types[q.type]=(types[q.type]||0)+1;
 assert.ok(q.prompt&&q.prompt.length>=15&&q.answer,'Missing prompt or answer: '+q.term);
 assert.ok(q.explanation&&q.explanation.length>=12,'Missing explanation: '+q.term);
 assert.equal(q.choices,undefined,'Rescue tasks should require typed words');
 if(q.type==='PARAPHRASE'){
  assert.ok(q.focus&&q.focus.length>=4,'Paraphrase target missing: '+q.term);
  assert.equal(q.prompt.split(q.focus).length,2,'Paraphrase target should occur once: '+q.term);
  assert.ok(q.target&&q.target.includes('____'),'Missing rephrased sentence: '+q.term);
 }
}
assert.deepEqual(types,{FORM:11,COLLOCATION:12,PARAPHRASE:11,CONTEXT:12});
assert.ok(html.includes("'<mark>'"),'Paraphrase focus should be highlighted');
assert.ok(html.includes("answerForm")&&html.includes("function submitAnswer("),'Form input must be supported');
assert.ok(html.includes("type:'wordhop-rescue-unit4-result'"),'The game should send its result to WordHop');
assert.ok(html.includes("wordhop.arcade.wordrescue.unit4.v1"),'High-score key missing');
assert.ok(html.includes('5 COINS'),'Coin reward rules must be presented');
assert.ok(html.includes("state.coinsTotal"),'Coin reward implementation missing');
const hazardsMatch=html.match(/const HAZARDS=(\{[\s\S]*?\});\s*const SEGMENT_PATTERNS=/);
assert.ok(hazardsMatch,'Hazard pool missing');
const hazards=new Function('return ('+hazardsMatch[1]+')')();
assert.equal(hazards.CITY.length,10);
assert.equal(hazards.FOREST.length,10);
assert.equal(new Set(hazards.CITY.map(x=>x.type)).size,10);
assert.equal(new Set(hazards.FOREST.map(x=>x.type)).size,10);
assert.ok(html.includes('JUMP AHEAD')||html.includes('JUMP'), 'Obstacle warning missing');
const scriptBlocks=[...html.matchAll(/<script(?: [^>]+)?>([\s\S]*?)<\/script>/g)].filter(m=>!m[0].includes('type="application/json"'));
for(const [i,script] of scriptBlocks.entries())new vm.Script(script[1],{filename:'word-rescue-inline-'+i+'.js'});
const defer=html.match(/(function postponeWord\(\)\{[\s\S]*?\n\})\s*function resolveQuestion\(/);
assert.ok(defer,'Later/Skip must be implemented');
const state={phase:'question',mode:'practice',lock:false,deck:[{term:'activate',sector:'CITY'},{term:'alarm',sector:'CITY'},{term:'pup',sector:'FOREST'}],i:0,missed:[],skipped:0,attempted:0,streak:3,score:100,qMistake:false,hinted:false};
const context={state,current:()=>state.deck[state.i],$:(selector)=>({textContent:'',className:'',focus(){}}),questionOverlay(){},status(){},playSound(){},updateHUD(){}};
vm.createContext(context);
vm.runInContext(defer[1]+'\npostponeWord();',context);
assert.deepEqual(state.deck.map(q=>q.term),['alarm','activate','pup'],'Skip should defer within the same stage');
assert.equal(state.i,0,'Skip must not increase progress');
assert.equal(state.phase,'question','Skip must not unlock the gate');
assert.equal(state.attempted,1,'Skip should count as an attempt');
assert.equal(state.skipped,1);
assert.equal(state.score,90);
state.i=1;
vm.runInContext('postponeWord();',context);
assert.equal(state.i,1,'Last word of a stage cannot be skipped');
assert.equal(state.skipped,1,'Last word should not be deferred');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
assert.ok(app.includes("id!=='rescue'||u.id==='bir-unit-4'"),'Rescue must appear only in Unit 4');
assert.ok(app.includes("mode==='rescue'&&route.unit.id!=='bir-unit-4'"),'Rescue start must be Unit 4 only');
assert.ok(app.includes('games/word-rescue-unit4.html?embed=1'));
assert.ok(app.includes("wordhop-rescue-unit4-result"));
assert.ok(app.includes('attempted>total+10000'),'Results must allow extra attempts from deferred words');
assert.ok(app.includes("localStorage.removeItem('wordhop.arcade.wordrescue.unit4.v1')"));
console.log('PASS: Unit 4 Word Rescue: 46 typed tasks, 11 highlighted paraphrases, 20 varied hazards, coin rewards, non-advancing Skip and WordHop result routing.');
